#!/usr/bin/env python3
"""Single source of truth for the pinned software stack.

`versions.json` is the authoritative list of pinned versions. Everything else is
generated from it: the APT package pins and the ARG/LABEL blocks in the
Dockerfile, requirements.in, and the README stack table. The
stack therefore cannot drift between the places it is written down.

Usage:
    python3 tools/versions.py check        # verify every generated block is current
    python3 tools/versions.py sync         # rewrite the generated files
    python3 tools/versions.py apt          # print the Dockerfile APT block
    python3 tools/versions.py args         # print the Dockerfile ARG block
    python3 tools/versions.py labels       # print the Dockerfile LABEL block
    python3 tools/versions.py readme       # print the README version table
    python3 tools/versions.py check-lock   # fail if the lock shadows a base package
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
VERSIONS_FILE = ROOT / "versions.json"

GENERATED_HEADER = (
    "GENERATED by tools/versions.py from versions.json - do not edit by hand."
)

APT_BEGIN = "# BEGIN GENERATED: tools/versions.py apt\n"
APT_END = "# END GENERATED\n"
ARGS_BEGIN = "# BEGIN GENERATED: tools/versions.py args\n"
ARGS_END = "# END GENERATED\n"
LABELS_BEGIN = "# BEGIN GENERATED: tools/versions.py labels\n"
LABELS_END = "# END GENERATED\n"
README_BEGIN = "<!-- versions:begin -->\n"
README_END = "<!-- versions:end -->\n"

BASE_CONSTRAINTS = ROOT / "docker" / "base-constraints.txt"


def base_owned() -> set[str]:
    """Names the base image ships, read from the generated base constraints.

    Derived, not hand-maintained: a hand-written list once declared `requests`
    base-owned although the base does not ship it, and would have dropped a
    package ComfyUI imports at startup.
    """
    if not BASE_CONSTRAINTS.is_file():
        raise SystemExit("docker/base-constraints.txt is missing; run `make base-constraints`")
    return {
        line.split("==")[0].strip().lower()
        for line in BASE_CONSTRAINTS.read_text(encoding="utf-8").splitlines()
        if "==" in line and not line.lstrip().startswith("#")
    }


def load() -> dict:
    with VERSIONS_FILE.open(encoding="utf-8") as handle:
        return json.load(handle)


def base_reference(data: dict) -> str:
    """Fully qualified, digest-pinned base image reference."""
    image = data["image"]
    reference = f'{image["base_image"]}:{image["base_version"]}'
    digest = image["base_digest"]
    if not digest.startswith("sha256:") or "REPLACE" in digest:
        raise SystemExit(
            "image.base_digest in versions.json is not a resolved digest.\n"
            "Publish the base image first, then run `make pin-base`."
        )
    return f"{reference}@{digest}"


def apt_block(data: dict) -> str:
    """APT sources frozen at one snapshot plus exact package versions.

    The base image already points apt at this snapshot, so these pins resolve
    against the same archive the base was built from. Writing the sources file
    here as well keeps the block self-contained if the base changes.
    """
    image = data["image"]
    series = image["ubuntu_series"]
    snapshot = image["ubuntu_snapshot"]
    packages = "".join(
        f"        {name}={version} \\\n" for name, version in data["apt"].items()
    ).rstrip(" \\\n")
    return (
        f"ARG APT_SNAPSHOT={snapshot}\n"
        "RUN set -eux; \\\n"
        "    printf '%s\\n' \\\n"
        "        'Types: deb' \\\n"
        '        "URIs: https://snapshot.ubuntu.com/ubuntu/${APT_SNAPSHOT}/" \\\n'
        f"        'Suites: {series} {series}-updates {series}-security' \\\n"
        "        'Components: main universe restricted multiverse' \\\n"
        "        'Signed-By: /usr/share/keyrings/ubuntu-archive-keyring.gpg' \\\n"
        "        > /etc/apt/sources.list.d/ubuntu.sources; \\\n"
        "    apt-get update; \\\n"
        "    apt-get install -y --no-install-recommends \\\n"
        f"{packages}; \\\n"
        "    rm -rf /var/lib/apt/lists/*\n"
    )


def args_block(data: dict) -> str:
    """The pinned base image and the build arguments derived from versions.json.

    BASE_IMAGE has to be declared before FROM to be usable there, and an ARG
    declared before FROM is not visible inside the stage, so everything the
    labels and RUN steps need is declared a second time after it. The block
    therefore emits the FROM line as well: the base digest is a pin, and a pin
    written in two places drifts.
    """
    sources = data["sources"]
    return (
        f"ARG BASE_IMAGE={base_reference(data)}\n"
        "FROM ${BASE_IMAGE}\n"
        "\n"
        "# Re-declared inside the stage: an ARG before FROM is not visible after it.\n"
        f"ARG IMAGE_VERSION={data['image']['version']}\n"
        "ARG IMAGE_REVISION=unknown\n"
        "ARG IMAGE_CREATED=1970-01-01T00:00:00Z\n"
        f"ARG COMFYUI_VERSION={sources['comfyui']['version']}\n"
        f"ARG COMFYUI_REVISION={sources['comfyui']['revision']}\n"
    )


def labels_block(data: dict) -> str:
    image = data["image"]
    comfyui = data["sources"]["comfyui"]
    labels = {
        "org.opencontainers.image.title": "comfyui-rocm",
        "org.opencontainers.image.description": (
            "ComfyUI with ROCm support for AMD Radeon GPUs"
        ),
        "org.opencontainers.image.source": (
            "https://github.com/HardAndHeavy/comfyui-rocm-docker"
        ),
        "org.opencontainers.image.url": "https://hub.docker.com/r/hardandheavy/comfyui-rocm",
        "org.opencontainers.image.documentation": (
            "https://github.com/HardAndHeavy/comfyui-rocm-docker#readme"
        ),
        "org.opencontainers.image.licenses": "Apache-2.0",
        "org.opencontainers.image.version": "${IMAGE_VERSION}",
        "org.opencontainers.image.revision": "${IMAGE_REVISION}",
        "org.opencontainers.image.created": "${IMAGE_CREATED}",
        "org.opencontainers.image.base.name": (
            f"{image['base_image']}:{image['base_version']}"
        ),
        "org.opencontainers.image.base.digest": image["base_digest"],
        "ru.hardandheavy.comfyui.version": comfyui["version"],
        "ru.hardandheavy.comfyui.revision": comfyui["revision"],
        "ru.hardandheavy.comfyui-manager.version": data["requirements"]["comfyui_manager"].lstrip("="),
        "ru.hardandheavy.state-directory": "/data",
    }
    lines = [f'{key}="{value}" \\' for key, value in labels.items()]
    return "LABEL " + "\n      ".join(lines).rstrip(" \\\n") + "\n"


def requirements_in(data: dict) -> str:
    """ComfyUI's runtime dependencies that the base image does not provide.

    Mirrors requirements.txt of the pinned ComfyUI revision minus everything the
    base ships (torch, numpy, transformers, Pillow, ...). Those are resolved
    against docker/base-constraints.txt and excluded from the lock by `make lock`.
    """
    image = data["image"]
    comfyui = data["sources"]["comfyui"]
    return (
        f"# {GENERATED_HEADER}\n"
        f"# ComfyUI {comfyui['version']} ({comfyui['revision']}) on\n"
        f"# {image['base_image']}:{image['base_version']}, CPython {image['python_version']}, Linux x86_64.\n"
        "# Base-image packages are omitted; `make lock` resolves against them.\n"
        + "".join(f"{name}{spec}\n" for name, spec in data["requirements"].items())
    )


def readme_table(data: dict) -> str:
    comfyui = data["sources"]["comfyui"]
    rows = [
        ("Base image", base_reference(data)),
        ("ComfyUI", f"{comfyui['version']} ({comfyui['revision'][:9]})"),
        ("ComfyUI Manager", data["requirements"]["comfyui_manager"].lstrip("=")),
        ("Python", data["image"]["python_version"]),
        ("Persistent state", "`/data`: models, custom_nodes, input, output, user, `.venv`, `home`"),
    ]
    body = "".join(f"| {name} | {version} |\n" for name, version in rows)
    return "| Component | Version |\n| --- | --- |\n" + body.rstrip("\n") + "\n"


def replace_between(text: str, begin: str, end: str, body: str) -> str:
    """Swap the content between two marker lines, keeping the markers."""
    head, marker, rest = text.partition(begin)
    if not marker:
        raise SystemExit(f"marker not found: {begin.strip()!r}")
    _, marker, tail = rest.partition(end)
    if not marker:
        raise SystemExit(f"marker not found: {end.strip()!r}")
    return head + begin + body + end + tail


def render(data: dict) -> dict[str, str]:
    """Every generated file, fully rendered: path -> expected content."""
    dockerfile = (ROOT / "Dockerfile").read_text(encoding="utf-8")
    dockerfile = replace_between(dockerfile, APT_BEGIN, APT_END, apt_block(data))
    dockerfile = replace_between(dockerfile, ARGS_BEGIN, ARGS_END, args_block(data))
    dockerfile = replace_between(dockerfile, LABELS_BEGIN, LABELS_END, labels_block(data))
    readme = (ROOT / "README.md").read_text(encoding="utf-8")
    readme = replace_between(readme, README_BEGIN, README_END, readme_table(data))
    return {
        "Dockerfile": dockerfile,
        "README.md": readme,
        "requirements.in": requirements_in(data),
    }


def sync() -> int:
    data = load()
    changed = []
    for name, content in render(data).items():
        path = ROOT / name
        if not path.exists() or path.read_text(encoding="utf-8") != content:
            path.write_text(content, encoding="utf-8")
            changed.append(name)
    print("updated: " + ", ".join(changed) if changed else "everything already current")
    return 0


def check() -> int:
    stale = [
        name
        for name, content in render(load()).items()
        if (ROOT / name).read_text(encoding="utf-8") != content
    ]
    if stale:
        print("out of date, run `make versions`: " + ", ".join(stale), file=sys.stderr)
        return 1
    print("versions.json is in sync")
    return 0


def check_lock() -> int:
    """Fail if the dependency lock reintroduces a base-owned package."""
    lock = ROOT / "requirements.lock"
    if not lock.is_file():
        print("requirements.lock is missing; run `make lock`", file=sys.stderr)
        return 1
    text = lock.read_text(encoding="utf-8")
    offenders = sorted(
        {
            line.split("==")[0].strip().lower()
            for line in text.splitlines()
            if "==" in line and not line.lstrip().startswith("#")
        }
        & base_owned()
    )
    if offenders:
        print(
            "requirements.lock pins packages owned by the base image: "
            + ", ".join(offenders)
            + "\nRegenerate with `make lock`, which excludes every base package.",
            file=sys.stderr,
        )
        return 1
    print("requirements.lock does not shadow base-image packages")
    return 0


def main(argv: list[str]) -> int:
    command = argv[1] if len(argv) > 1 else "check"
    data = load()
    printers = {
        "apt": apt_block,
        "args": args_block,
        "labels": labels_block,
        "readme": readme_table,
    }
    if command in printers:
        print(printers[command](data), end="")
        return 0
    if command == "sync":
        return sync()
    if command == "check":
        return check()
    if command == "check-lock":
        return check_lock()
    print(__doc__, file=sys.stderr)
    return 2


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
