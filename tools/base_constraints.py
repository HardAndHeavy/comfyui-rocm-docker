#!/usr/bin/env python3
"""Generate the two constraint files from what the base image really ships.

docker/base-constraints.txt
    Every distribution installed in the base image's /opt/venv, at its exact
    version. Feeds `make lock` only: the ComfyUI lock is resolved *against* the
    base, so it agrees with numpy, transformers, torch, ... instead of pulling a
    second copy, and every name listed here is excluded from the lock output.

docker/constraints.txt
    The protected subset: the GPU stack and the libraries whose replacement
    breaks it. Installed into the image as PIP_CONSTRAINT/UV_CONSTRAINT, so a
    custom node that asks ComfyUI Manager for another torch gets a resolver
    error instead of a CUDA wheel. Anything not listed here may still be
    upgraded by a node; the newer copy lands in the /data overlay and the image
    layer is left untouched.

Both files are produced from the registry image, never typed by hand. The
Dockerfile fails the build if the installed base disagrees with the protected
set, and `make check` fails if either file is stale against the pinned digest.

Usage:
    python3 tools/base_constraints.py           # regenerate both files
    python3 tools/base_constraints.py --check   # fail if they are stale
"""

from __future__ import annotations

import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))

from versions import base_reference, load  # noqa: E402

BASE_FILE = ROOT / "docker" / "base-constraints.txt"
PROTECTED_FILE = ROOT / "docker" / "constraints.txt"

# Installer tooling is constrained too. At lock time this keeps the lock from
# reinstalling a different pip or setuptools over the base's own copy; it does
# not restrict what a node does at runtime, because the runtime constraint file
# (docker/constraints.txt) only carries the protected GPU subset.
PROTECTED = re.compile(
    r"^("
    r"torch|torchvision|torchaudio|triton|"
    r"rocm|rocm-bootstrap|rocm-sdk-.+|"
    r"amd-torch-device-.+|amd-torchvision-device-.+|"
    r"llama-cpp-python|"
    r"numpy|transformers|tokenizers|safetensors|accelerate|peft|"
    r"huggingface-hub|sentencepiece|scipy|protobuf"
    r")$"
)


def normalize(name: str) -> str:
    """PEP 503 normalized project name."""
    return re.sub(r"[-_.]+", "-", name).lower()


def installed(reference: str) -> dict[str, str]:
    result = subprocess.run(
        [
            "docker", "run", "--rm", "--entrypoint", "python", reference,
            "-m", "pip", "list", "--format=json", "--disable-pip-version-check",
        ],
        capture_output=True,
        text=True,
    )
    if result.returncode != 0:
        raise SystemExit(f"could not list packages in {reference}:\n{result.stderr.strip()}")
    return {
        normalize(entry["name"]): entry["version"]
        for entry in json.loads(result.stdout)
    }


def render(reference: str, packages: dict[str, str]) -> dict[Path, str]:
    names = sorted(packages)
    base = (
        "# GENERATED by tools/base_constraints.py (`make base-constraints`) - do not edit.\n"
        f"# Every distribution shipped by {reference}.\n"
        "# Lock-time only: `make lock` resolves against these and excludes them.\n"
        + "".join(f"{name}=={packages[name]}\n" for name in names)
    )
    protected = (
        "# GENERATED by tools/base_constraints.py (`make base-constraints`) - do not edit.\n"
        f"# GPU stack shipped by {reference}.\n"
        "# Installed as PIP_CONSTRAINT/UV_CONSTRAINT: no pip run inside the\n"
        "# container, including ComfyUI Manager's, may replace these versions.\n"
        + "".join(f"{name}=={packages[name]}\n" for name in names if PROTECTED.match(name))
    )
    return {BASE_FILE: base, PROTECTED_FILE: protected}


def main(argv: list[str]) -> int:
    reference = base_reference(load())
    files = render(reference, installed(reference))
    if "--check" in argv[1:]:
        stale = [p.name for p, text in files.items()
                 if not p.is_file() or p.read_text(encoding="utf-8") != text]
        if stale:
            print("stale, run `make base-constraints`: " + ", ".join(stale), file=sys.stderr)
            return 1
        print("constraint files match the base image")
        return 0
    for path, text in files.items():
        path.write_text(text, encoding="utf-8")
        print(f"wrote {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
